import json, os
d = json.load(open(r'C:\Users\Admin\pxrt_dev\launch_fields.json', encoding='utf-8'))
kinds = {}
for k, v in d.items():
    kinds.setdefault(v.get('kind'), []).append(k)
print({k: len(v) for k, v in kinds.items()})
print(kinds)
lines = ['-- generated by gen_launch.py from re_launch (CWeaponLaunch field map; offsets relative to launch block)', 'return {']
for k, v in sorted(d.items(), key=lambda kv: kv[1]['off']):
    kind = v.get('kind', 'int')
    lines.append('  [%s] = { off = %d, kind = %s },' % (json.dumps(k), v['off'], json.dumps(kind)))
lines.append('}')
os.makedirs(r'C:\Users\Admin\pxrt_dev\out\lualibs', exist_ok=True)
open(r'C:\Users\Admin\pxrt_dev\out\lualibs\pxl_launch.lua', 'w', newline='\n').write('\n'.join(lines) + '\n')
print('written')
