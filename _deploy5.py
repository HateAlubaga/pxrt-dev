"""Deploy round 5: quad renderer (pxrt_e_quads.lua + QuadRender in wkJellyWorm.dll) on top of round 4.
Runtime files + regenerated pxl_/pxp_ files (only those already deployed) + DLL.
Backup + manifest in pxrt_backup\\<stamp>_quads."""
import os, shutil, json, time, subprocess, sys, hashlib
DEV = r'C:\Users\Admin\pxrt_dev'
sys.path.insert(0, DEV)
import pxgen
GAME = r'C:\Program Files (x86)\by Decepticon\Worms Armageddon'
LL = os.path.join(GAME, 'jelly', 'lualibs')
BK = r'C:\Users\Admin\pxrt_backup'

out = subprocess.run(['tasklist'], capture_output=True, text=True, errors='replace').stdout.lower()
if any(l.startswith(('wa.exe', 'worms')) for l in out.splitlines()):
    sys.exit('WA running')

def md5b(b):
    return hashlib.md5(b).hexdigest()

new = {}   # dst name -> bytes
new['pxrt.lua'] = open(os.path.join(DEV, 'pxrt_core.lua'), 'rb').read()
for f in os.listdir(DEV):
    if (f.startswith('pxrt_e_') and f.endswith('.lua')) or f in ('pxrt_engine.lua', 'pxboot.lua'):
        new[f] = open(os.path.join(DEV, f), 'rb').read()
libdir = pxgen.write_libs()
for f in os.listdir(libdir):
    if f.startswith('pxl_') and os.path.exists(os.path.join(LL, f)):
        new[f] = open(os.path.join(libdir, f), 'rb').read()
for f in os.listdir(LL):
    if f.startswith('pxp_') and f.endswith('.lua'):
        pkg = f[4:-4]
        s = '-- generated by pxdeploy.py: ProjectX scripts of package %s\nreturn %s\n' % (pkg, pxgen.gen_pkg_table(pkg))
        new[f] = s.encode('utf-8')

stamp = time.strftime('%Y%m%d_%H%M%S')
bk = os.path.join(BK, stamp + '_quads')
os.makedirs(os.path.join(bk, 'lualibs'))
rep, created, same = [], [], 0
for dst, data in sorted(new.items()):
    d = os.path.join(LL, dst)
    if os.path.exists(d):
        old = open(d, 'rb').read()
        if old == data:
            same += 1
            continue
        shutil.copy2(d, os.path.join(bk, 'lualibs', dst))
        rep.append('lualibs\\' + dst)
    else:
        created.append('lualibs\\' + dst)
    with open(d, 'wb') as fh:
        fh.write(data)
    if md5b(open(d, 'rb').read()) != md5b(data):
        sys.exit('copy mismatch ' + dst)
DLL_SRC = r'C:\Users\Admin\Projects\worms-modding-lab\sources\wkJellyWorm\build\Release\wkJellyWorm.dll'
dll = os.path.join(GAME, 'wkJellyWorm.dll')
shutil.copy2(dll, os.path.join(bk, 'wkJellyWorm.dll'))
shutil.copy2(dll, dll + '.bak_claude_' + stamp)
shutil.copyfile(DLL_SRC, dll)
if md5b(open(DLL_SRC, 'rb').read()) != md5b(open(dll, 'rb').read()):
    sys.exit('dll copy mismatch')
json.dump({'jelly': os.path.join(GAME, 'jelly'), 'created': created, 'replaced': rep, 'game_replaced': ['wkJellyWorm.dll']},
          open(os.path.join(bk, 'manifest.json'), 'w'), indent=1)
print('deployed', bk, 'replaced', len(rep), 'created', len(created), 'unchanged', same, 'dll', md5b(open(dll, 'rb').read()))
