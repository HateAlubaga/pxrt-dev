"""Build pxrt_wnames.lua: weapon name registered by each package's main.lua -> ProjectX's own weapon name.

px2jelly registered weapons under names made from the .bin file name ("Balloon W", "Holy Bazooka Wep"), while the
ProjectX scripts test the real names stored in the .bin trailer ("Hot Air Balloon", "Holy Bazooka"), so
CWeapon::CheckName never matched. The runtime reads this table to show scripts the ProjectX names.

usage: py -3.10 pxwnames.py [out.lua]   (default: pxrt_wnames.lua next to this script)
"""
import os, re, struct, sys
GAME = r'C:\Program Files (x86)\by Decepticon\Worms Armageddon'
PKGS = os.path.join(GAME, 'jelly', 'packages')
TRAILER = 0x1E0   # PxWeaponArt.cpp kTrailerOffset
REG = re.compile(r'registerCustomWeapon\((\w+),\s*"[^"]*",\s*"([^"]*)",\s*"([^"]*)"\)')


def px_name(path):
    d = open(path, 'rb').read()
    pos = TRAILER + 4
    if pos + 4 > len(d):
        return None
    n = struct.unpack_from('<I', d, pos)[0]
    if n > 260 or pos + 4 + n > len(d):
        return None
    return d[pos + 4:pos + 4 + n].split(b'\0')[0].decode('latin-1')


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pxrt_wnames.lua')
    names = {}
    conflicts = []
    for pkg in sorted(os.listdir(PKGS)):
        pdir = os.path.join(PKGS, pkg)
        if not os.path.isdir(pdir):
            continue
        for ver in sorted(os.listdir(pdir)):
            d = os.path.join(pdir, ver)
            ml = os.path.join(d, 'main.lua')
            if not os.path.isfile(ml):
                continue
            src = open(ml, encoding='utf-8', errors='replace').read()
            regs = REG.findall(src)
            rawd = os.path.join(d, 'weapons_raw')
            bins = sorted(f for f in os.listdir(rawd) if f.lower().endswith('.bin')) if os.path.isdir(rawd) else []
            for var, n1, _n2 in regs:
                # <var>.bin; else the one bin whose name starts with <var> ("superjet" -> superjet_WEAP.bin);
                # else the only bin of a package registering one weapon
                b = None
                if var + '.bin' in bins:
                    b = var + '.bin'
                else:
                    pre = [f for f in bins if f.lower().startswith(var.lower())]
                    if len(pre) == 1:
                        b = pre[0]
                    elif len(bins) == 1 and len(regs) == 1:
                        b = bins[0]
                if not b:
                    continue
                b = os.path.join(rawd, b)
                real = px_name(b)
                if not real or real.strip() == n1.strip():
                    continue
                real = real.strip()
                old = names.get(n1)
                if old and old != real:
                    conflicts.append((n1, old, real, pkg))
                    continue
                names[n1] = real
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('-- generated by pxwnames.py: registered weapon name -> ProjectX weapon name (from weapons_raw/*.bin)\n')
        f.write('return {\n')
        for k in sorted(names):
            f.write('  [%s] = %s,\n' % (lua_str(k), lua_str(names[k])))
        f.write('}\n')
    print('%d names -> %s' % (len(names), out))
    for c in conflicts:
        print('conflict: %r -> %r / %r (%s)' % c)


main()
