"""Deploy round 8 (2026-10-13): packages that became convertible after the parser fixes (digit-leading identifiers,
stray ')', implicit '}' at EOF, 'require a:') and the two quarantined packages the harness now runs clean
(was_counters, script_scoreboard: the harness started mid-turn). Runtime files are unchanged.

For each package: pxp_<pkg>.lua + converted main.lua (pxdeploy.transform); pxl_<lib>.lua for required libraries
that are not in the game yet. Quarantined packages move back from packages_disabled first.
Backup + manifest in pxrt_backup\\<stamp>_r8. Dry run unless --apply."""
import os, sys, json, time, shutil, hashlib
DEV = r'C:\Users\Admin\pxrt_dev'
sys.path.insert(0, DEV)
import pxgen, pxdeploy, pxquarantine
from paths import *

PKGS = ['map_object_ktk_control', 'scheme_ktk', 'scheme_ktk_live', 'scheme_ktk_zomb', 'script_agility',
        'scheme_basketball', 'script_possessed_objects', 'utility_shield_gun', 'weapon_air_steps',
        'script_other_drums', 'weapon_air_911']
RESTORE = ['was_counters', 'script_scoreboard']
LL = os.path.join(JELLY, 'lualibs')
PK = os.path.join(JELLY, 'packages')
DIS = os.path.join(JELLY, 'packages_disabled')
BK = r'C:\Users\Admin\pxrt_backup'
apply = '--apply' in sys.argv


def md5b(b):
    return hashlib.md5(b).hexdigest()


def libs_of(names):
    seen, todo = set(), list(names)
    while todo:
        n = todo.pop()
        d = pxgen.lib_dir(n) if n in pxgen.all_libs() and not os.path.isdir(pxgen.pkg_dir(n)) else pxgen.pkg_dir(n)
        if not os.path.exists(os.path.join(d, 'pxchunks.json')):
            d = pxgen.lib_dir(n)
        for l in pxgen.read_chunks(d)[0]:
            if l not in seen:
                seen.add(l)
                todo.append(l)
    return seen


if apply and pxdeploy.wa_running():
    sys.exit('WA.exe is running - close the game first')

new = {}      # absolute dst path -> bytes
for pkg in PKGS + RESTORE:
    base = DIS if pkg in RESTORE else PK
    fp = os.path.join(base, pkg, '0.0.1', 'main.lua')
    src = open(fp, encoding='utf-8', errors='surrogateescape', newline='').read()
    conv, err = pxdeploy.transform(src, pkg)
    if conv is None:
        sys.exit('%s: %s' % (pkg, err))
    e = pxdeploy.lua_compiles(conv)
    if e:
        sys.exit('%s: converted main.lua does not compile: %s' % (pkg, e))
    new[os.path.join(PK, pkg, '0.0.1', 'main.lua')] = conv.encode('utf-8', 'surrogateescape')
    new[os.path.join(LL, 'pxp_%s.lua' % pkg)] = ('-- generated by pxdeploy.py: ProjectX scripts of package %s\nreturn %s\n'
                                                % (pkg, pxgen.gen_pkg_table(pkg))).encode('utf-8')
all_libs = set(pxgen.all_libs())
for l in sorted(libs_of(PKGS + RESTORE)):
    dst = os.path.join(LL, 'pxl_%s.lua' % l)
    if l in all_libs and not os.path.exists(dst):
        new[dst] = pxgen.gen_lib(l).encode('utf-8')

for d in sorted(new):
    state = 'replace' if os.path.exists(d) or any(d.startswith(os.path.join(PK, r) + os.sep) for r in RESTORE) else 'create'
    print('%-8s %s' % (state, os.path.relpath(d, JELLY)))
print('restore from packages_disabled:', RESTORE)
if not apply:
    sys.exit('dry run; pass --apply')

stamp = time.strftime('%Y%m%d_%H%M%S')
bk = os.path.join(BK, stamp + '_r8')
os.makedirs(bk)
pxquarantine.restore(RESTORE)
manifest = {'replaced': [], 'created': [], 'restored_from_disabled': RESTORE}
for d, data in sorted(new.items()):
    rel = os.path.relpath(d, JELLY)
    if os.path.exists(d):
        b = os.path.join(bk, rel)
        os.makedirs(os.path.dirname(b), exist_ok=True)
        shutil.copy2(d, b)
        manifest['replaced'].append(rel)
    else:
        manifest['created'].append(rel)
    with open(d, 'wb') as fh:
        fh.write(data)
    if md5b(open(d, 'rb').read()) != md5b(data):
        sys.exit('copy mismatch ' + rel)
json.dump(manifest, open(os.path.join(bk, 'manifest.json'), 'w', encoding='utf-8'), indent=1)
open(os.path.join(bk, 'RESTORE.txt'), 'w', encoding='utf-8').write(
    'Rollback: copy every file under this folder back into jelly\\ (same relative path), delete the files listed as\n'
    '"created" in manifest.json, then run: py -3.10 pxquarantine.py move was_counters script_scoreboard\n')
print('deployed %d files, backup %s' % (len(new), bk))
